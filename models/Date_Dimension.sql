WITH CTE AS (
SELECT TO_TIMESTAMP(START_DATE) AS START_DATE1,
DATE(TO_TIMESTAMP(START_DATE)) AS START_DATE,
HOUR(tO_TIMESTAMP(START_DATE)) AS HOURS,
DAYOFWEEK(tO_TIMESTAMP(START_DATE)) AS DAY_OF_THE_WEEK,

DAYNAME(TO_TIMESTAMP(START_DATE)) AS DAY_NAME,
CASE 
WHEN DAYNAME(TO_TIMESTAMP(START_DATE)) IN ('Sat','Sun')
THEN 'WEEKEND'
ELSE 'WEEKDAY'
END AS DAY_TYPE,

MONTH(TO_TIMESTAMP(START_DATE)) AS MONTH,
CASE 
WHEN MONTH(TO_TIMESTAMP(START_DATE)) IN (12,1,2)
THEN 'WINTER'
WHEN MONTH(TO_TIMESTAMP(START_DATE)) IN (3,4,5)
THEN 'SPRING' 
WHEN MONTH(TO_TIMESTAMP(START_DATE)) IN (6,7,8)
THEN 'SUMMER' 
ELSE 'AUTOMUN'
END AS SEASON
FROM {{ source('DEMO', 'CITI_BIKE_MASTER') }}
WHERE START_DATE <> 'started_at'
)

SELECT * FROM CTE
